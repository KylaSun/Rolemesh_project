import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {toFrontendCandidates,toFrontendCandidateStates} from './bridge.mjs';
const response=JSON.parse(readFileSync(new URL('../examples/profiles_output.json',import.meta.url),'utf8'));
const metadata=new Map(response.comparisons.map(r=>[r.profile_id,{display_name:r.profile_id}]));
const cards=toFrontendCandidates(response,metadata);
assert.equal(cards.length,response.recommendations.length);
assert.deepEqual(cards.map(r=>r.profile_id),response.recommendations.map(r=>r.profile_id));
assert.ok(cards.every(r=>Number.isInteger(r.match)));
assert.throws(()=>toFrontendCandidates(response,new Map()),/metadata/);
const bad=structuredClone(response);bad.recommendations[0].match=null;
assert.throws(()=>toFrontendCandidates(bad,metadata));
const cross=structuredClone(response);cross.recommendations[0].role_id='other';
assert.throws(()=>toFrontendCandidates(cross,metadata));
const zero=structuredClone(response);zero.recommendations[0].match=0;
assert.equal(toFrontendCandidates(zero,metadata)[0].match,0);
const states=toFrontendCandidateStates(response);
assert.equal(states.find(x=>x.profile_id==='profile.unknown').state,'needs_confirmation');
assert.equal(states.find(x=>x.profile_id==='profile.failed').state,'not_eligible');
assert.equal(states.find(x=>x.profile_id==='profile.provisional').state,'incomplete_scoring');
assert.deepEqual(toFrontendCandidates({...response,recommendations:[],comparisons:[]},metadata),[]);
assert.throws(()=>toFrontendCandidates({...response,contract_version:'next'},metadata));
console.log('Candidate adapter: 12 checks passed');
